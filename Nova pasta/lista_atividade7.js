let numero = parseInt(prompt("Digite um número de 1 a 20:"));

switch (numero) {
    case 1:
        alert("Um");
        break;
    case 2:
        alert("Dois");
        break;
    case 3:
        alert("Três");
        break;
    case 4:
        alert("Quatro");
        break;
    case 5:
        alert("Cinco");
        break;
    case 6:
        alert("Seis");
        break;
    case 7:
        alert("Sete");
        break;
    case 8:
        alert("Oito");
        break;
    case 9:
        alert("Nove");
        break;
    case 10:
        alert("Dez");
        break;
    case 11:
        alert("Onze");
        break;
    case 12:
        alert("Doze");
        break;
    case 13:
        alert("Treze");
        break;
    case 14:
        alert("Quatorze");
        break;
    case 15:
        alert("Quinze");
        break;
    case 16:
        alert("Dezesseis");
        break;
    case 17:
        alert("Dezessete");
        break;
    case 18:
        alert("Dezoito");
        break;
    case 19:
        alert("Dezenove");
        break;
    case 20:
        alert("Vinte");
        break;
    default:
        alert("Número inválido! Digite de 1 a 20.");
}