// 1. Criar um Array com cinco nomes de cidades
let cidades = ["Porto Alegre", "São Paulo", "Rio de Janeiro", "Curitiba", "Florianópolis"];

// 2. Mostrar todos os nomes no console
console.log("Cidades cadastradas:");
console.log(cidades);

// 3. Adicionar mais uma cidade
cidades.push("Salvador");

// 4. Remover a primeira cidade
cidades.shift();

// 5. Mostrar a quantidade de cidades cadastradas
console.log("Quantidade de cidades cadastradas:", cidades.length);